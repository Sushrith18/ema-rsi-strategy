"""Portfolio simulation and performance metrics for the trading strategies."""

from __future__ import annotations

import numpy as np
import pandas as pd


def run_backtest(
    df: pd.DataFrame, initial_capital: float = 100_000
) -> tuple[pd.Series, pd.Series, pd.DataFrame]:
    """Run a close-to-close, long-only backtest.

    The input must contain ``Close`` and the 0/1 ``position`` generated by
    :func:`strategy.generate_signals`. Returns the equity curve, daily
    strategy returns, and a completed trade log.
    """
    if initial_capital <= 0:
        raise ValueError("initial_capital must be positive.")
    required_columns = {"Close", "position"}
    missing_columns = required_columns.difference(df.columns)
    if missing_columns:
        raise ValueError(f"DataFrame is missing columns: {sorted(missing_columns)}.")
    if df.empty:
        empty = pd.Series(dtype=float, name="Equity")
        return empty, empty.rename("Strategy Return"), pd.DataFrame(
            columns=["Entry Date", "Exit Date", "Entry Price", "Exit Price", "Return %"]
        )

    prices = df["Close"].astype(float)
    positions = df["position"].astype(int).clip(0, 1)
    daily_returns = prices.pct_change().fillna(0).mul(positions)
    daily_returns.name = "Strategy Return"
    equity_curve = initial_capital * (1 + daily_returns).cumprod()
    equity_curve.name = "Equity"

    trades: list[dict[str, object]] = []
    entry_date = None
    entry_price = None
    for date, row in df.assign(position=positions).iterrows():
        if row["position"] == 1 and entry_date is None:
            entry_date = date
            entry_price = float(row["Close"])
        elif row["position"] == 0 and entry_date is not None:
            exit_price = float(row["Close"])
            trades.append(
                {
                    "Entry Date": entry_date,
                    "Exit Date": date,
                    "Entry Price": entry_price,
                    "Exit Price": exit_price,
                    "Return %": (exit_price / entry_price - 1) * 100,
                }
            )
            entry_date = None
            entry_price = None

    # Close any open trade at the final available price.
    if entry_date is not None:
        exit_price = float(prices.iloc[-1])
        trades.append(
            {
                "Entry Date": entry_date,
                "Exit Date": prices.index[-1],
                "Entry Price": entry_price,
                "Exit Price": exit_price,
                "Return %": (exit_price / entry_price - 1) * 100,
            }
        )

    trade_log = pd.DataFrame(
        trades,
        columns=["Entry Date", "Exit Date", "Entry Price", "Exit Price", "Return %"],
    )
    return equity_curve, daily_returns, trade_log


def calculate_metrics(
    df: pd.DataFrame,
    equity_curve: pd.Series,
    daily_returns: pd.Series,
    trade_log: pd.DataFrame,
    initial_capital: float = 100_000,
) -> dict[str, float]:
    """Calculate returns, risk, and trade statistics for a backtest."""
    if df.empty or equity_curve.empty:
        return {
            "Strategy Return": 0.0,
            "Buy & Hold Return": 0.0,
            "CAGR": 0.0,
            "Number of Trades": 0.0,
            "Win Rate": 0.0,
            "Max Drawdown": 0.0,
            "Sharpe Ratio": 0.0,
        }

    close = df["Close"].astype(float)
    buy_and_hold_return = (close.iloc[-1] / close.iloc[0] - 1) * 100
    strategy_return = (equity_curve.iloc[-1] / initial_capital - 1) * 100
    years = max((equity_curve.index[-1] - equity_curve.index[0]).days / 365.25, 0)
    cagr = (
        ((equity_curve.iloc[-1] / initial_capital) ** (1 / years) - 1) * 100
        if years > 0
        else 0.0
    )
    drawdown = equity_curve / equity_curve.cummax() - 1
    sharpe = (
        np.sqrt(252) * daily_returns.mean() / daily_returns.std()
        if daily_returns.std() != 0
        else 0.0
    )
    win_rate = (
        float((trade_log["Return %"] > 0).mean() * 100)
        if not trade_log.empty
        else 0.0
    )
    return {
        "Strategy Return": float(strategy_return),
        "Buy & Hold Return": float(buy_and_hold_return),
        "CAGR": float(cagr),
        "Number of Trades": float(len(trade_log)),
        "Win Rate": win_rate,
        "Max Drawdown": float(drawdown.min() * 100),
        "Sharpe Ratio": float(sharpe),
    }
